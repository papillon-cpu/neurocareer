/**
 * Проверка текста вакансии и ответов AI на признаки, по которым подбирать людей нельзя
 * (пол, возраст, национальность, религия, здоровье, семейное положение, внешность).
 * Это страховка, а не полный фильтр: окончательное решение о вакансии принимает модерация.
 */
// \b в JS не работает с кириллицей, поэтому границы слов заданы через lookbehind/lookahead.
const L = String.raw`(?<![а-яёa-z])`;
const R = String.raw`(?![а-яёa-z])`;

const SENSITIVE: { label: string; re: RegExp }[] = [
  {
    label: "пол",
    re: new RegExp(
      String.raw`(только|исключительно|предпочтительно|желательно)\s+(мужчин|женщин|девушк|парн)|${L}(мужчин|женщин|девушк|парн)[а-яё]*\s.{0,25}(требуется|ищем|приглашаем|нужн)|пол:\s*(м|ж|муж|жен)`,
      "i",
    ),
  },
  {
    label: "возраст",
    re: new RegExp(
      String.raw`(до|не\s+старше|не\s+моложе)\s+\d{2}\s*(лет|года)|возраст\s*(до|от|:)|молод(ой|ая|ые)\s+(коллектив|команд|специалист)|${L}молодых?${R}`,
      "i",
    ),
  },
  { label: "национальность", re: /национальност|славянск/i },
  { label: "религия", re: /вероисповедани|религиозн|православн|мусульман|христианин|иудей/i },
  { label: "здоровье", re: new RegExp(String.raw`${L}здоров(ый|ая|ые|ым)${R}|инвалид|беременн`, "i") },
  { label: "семейное положение", re: /семейн(ое|ым)\s+положени|без\s+детей|замужем|женат|холост|незамужн/i },
  { label: "внешность", re: /приятн(ая|ой)\s+внешност|привлекательн|внешность\s*:/i },
];

/** Названия признаков, которые нашлись в тексте. Пустой список — явных проблем нет. */
export function sensitiveFindings(text: string): string[] {
  return SENSITIVE.filter((s) => s.re.test(text)).map((s) => s.label);
}

/**
 * Для текстов, которые написал AI: кроме признаков выше нельзя обещать исход найма
 * («вероятность найма», проценты успеха), давать оценку личности и ссылаться на внешние адреса.
 */
const AI_FORBIDDEN = new RegExp(
  String.raw`вероятност[ьи]\s+(найма|успеха|принятия)|шанс(ы|ов)?\s+на\s+(найм|успех)|гарантир|обязательно\s+(нанять|взять)|рекомендуем\s+(отказать|не\s+нанимать)|https?://|(?<![a-z])IQ(?![a-z])|диагноз`,
  "i",
);

export function aiTextProblems(text: string): string[] {
  const problems = sensitiveFindings(text);
  if (AI_FORBIDDEN.test(text)) problems.push("недопустимая формулировка");
  return problems;
}
